import { describe, it, expect } from "vitest";
import { parse, Root } from "protobufjs";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  annotateProto,
  buildOptionsProto,
  METADATA_OPTIONS_PROTO_PATH,
  protoOptionName,
  type ProtoOptionDefinition,
} from "@/lib/metadata-attributes/protobuf-options";
import { PAYPAL_SECURITY_CLASSIFICATION_PACK } from "@/lib/metadata-attributes/packs/paypal-security-classification";
import type { SuperSchemaField, SuperSchemaModel } from "@/types/super-schema-model";

const PACK_DEF: ProtoOptionDefinition = { ...PAYPAL_SECURITY_CLASSIFICATION_PACK.definitions[0], protobufOptionNumber: 50000 };
const OWNER: ProtoOptionDefinition = {
  key: "x-owner",
  valueSchema: { type: "object", properties: { team: { type: "string" }, tier: { type: "integer" }, contacts: { type: "array", items: { type: "string" } } } },
  targets: ["entity"],
  scope: "schema",
  protobufOptionNumber: 50001,
};
const REVIEW: ProtoOptionDefinition = { key: "x-review-note", valueSchema: { type: "string" }, targets: ["field"], scope: "internal", protobufOptionNumber: 50002 };
const TAGS: ProtoOptionDefinition = { key: "x-tags", valueSchema: { type: "array", items: { type: "string" } }, targets: ["field"], scope: "schema", protobufOptionNumber: 50003 };
const NESTED: ProtoOptionDefinition = {
  key: "x-lineage",
  valueSchema: {
    type: "object",
    properties: {
      source: { type: "object", properties: { system: { type: "string" }, ratio: { type: "number" }, live: { type: "boolean" } } },
      hops: { type: "array", items: { type: "object", properties: { name: { type: "string" } } } },
    },
  },
  targets: ["field", "entity"],
  scope: "schema",
  protobufOptionNumber: 50004,
};

const ext = (openapi: Record<string, unknown>) => ({ typespec: { extensions: { openapi } } });
const field = (name: string, decorators?: unknown): SuperSchemaField =>
  ({ name, type: "string", nullable: false, isKey: false, classification: null, description: "", decorators }) as unknown as SuperSchemaField;
const model = (fields: SuperSchemaField[], entityExtensions?: Record<string, unknown>): SuperSchemaModel =>
  ({
    entity: { id: "e1", name: "Customer", description: "", metadata: entityExtensions ? { custom: { extensions: entityExtensions } } : null },
    fields,
  }) as unknown as SuperSchemaModel;

const PROTO = `// Generated by Microsoft TypeSpec

syntax = "proto3";

// A customer
message Customer {
  string email = 1;
  repeated string tags = 2;
  string note = 3;
  string first_name = 4;
}
`;

/** Parses the options proto and the annotated proto into one root with the real descriptor.proto, and resolves every type. */
function parseTogether(...files: string[]): Root {
  const root = new Root();
  const descriptor = readFileSync(join(process.cwd(), "node_modules/protobufjs/google/protobuf/descriptor.proto"), "utf8");
  parse(descriptor, root, { keepCase: true });
  for (const f of files) parse(f, root, { keepCase: true });
  root.resolveAll();
  return root;
}

describe("protoOptionName", () => {
  it("splits camelCase to snake, replaces non-alphanumerics and lowercases", () => {
    expect(protoOptionName("x-securityClassification")).toBe("x_security_classification");
    expect(protoOptionName("x-owner.team")).toBe("x_owner_team");
    expect(protoOptionName("x-HTTPStatus")).toBe("x_http_status");
  });
});

describe("buildOptionsProto", () => {
  it("the pack definition: a value message and a FieldOptions extension at its number", () => {
    const out = buildOptionsProto([PACK_DEF], ["x-securityClassification"]);
    expect(out.path).toBe(METADATA_OPTIONS_PROTO_PATH);
    expect(out.path).toBe("superschema/metadata_options.proto");
    expect(out.content).toContain('syntax = "proto3";');
    expect(out.content).toContain("package superschema.metadata;");
    expect(out.content).toContain('import "google/protobuf/descriptor.proto";');
    expect(out.content).toContain("message XSecurityClassificationValue {\n  string data_class = 1;\n  string data_category = 2;\n}");
    expect(out.content).toContain("extend google.protobuf.FieldOptions {\n  XSecurityClassificationValue x_security_classification = 50000;\n}");
    expect(out.content.replace(/\s+/g, " ")).toContain("message XSecurityClassificationValue { string data_class = 1; string data_category = 2; }");
    expect(out.content.replace(/\s+/g, " ")).toContain("extend google.protobuf.FieldOptions { XSecurityClassificationValue x_security_classification = 50000; }");
    expect(() => parseTogether(out.content)).not.toThrow();
  });

  it("maps types: integer int64, number double, boolean bool, arrays repeated, nested objects nested messages; entity defs extend MessageOptions", () => {
    const out = buildOptionsProto([OWNER, NESTED, TAGS], ["x-owner", "x-lineage", "x-tags"]);
    expect(out.content).toContain("message XOwnerValue {\n  string team = 1;\n  int64 tier = 2;\n  repeated string contacts = 3;\n}");
    expect(out.content).toContain(
      "message XLineageValue {\n  message Source {\n    string system = 1;\n    double ratio = 2;\n    bool live = 3;\n  }\n  message Hops {\n    string name = 1;\n  }\n  Source source = 1;\n  repeated Hops hops = 2;\n}"
    );
    expect(out.content).toContain("extend google.protobuf.MessageOptions {\n  XOwnerValue x_owner = 50001;\n  XLineageValue x_lineage_message = 50004;\n}");
    // Extensions (and value messages) are listed by option number.
    expect(out.content).toContain("extend google.protobuf.FieldOptions {\n  repeated string x_tags = 50003;\n  XLineageValue x_lineage = 50004;\n}");
    expect(out.content.indexOf("message XOwnerValue")).toBeLessThan(out.content.indexOf("message XLineageValue"));
    const root = parseTogether(out.content);
    expect(root.lookup("superschema.metadata.x_owner")).not.toBeNull();
  });

  it("only used keys; never an internal one; a definition without a number is skipped with a warning", () => {
    const warnings: string[] = [];
    const out = buildOptionsProto([PACK_DEF, REVIEW, { ...OWNER, protobufOptionNumber: null }, TAGS], ["x-securityClassification", "x-review-note", "x-owner"], warnings);
    expect(out.content).not.toContain("x_review_note");
    expect(out.content).not.toContain("x_tags");
    expect(out.content).not.toContain("x_owner");
    expect(warnings.some((w) => w.includes("x-owner") && w.includes("option number"))).toBe(true);
    expect(warnings.some((w) => w.includes("x-review-note"))).toBe(false);
  });
});

describe("annotateProto", () => {
  const customer = model(
    [
      field("email", ext({ "x-securityClassification": { data_class: "class2", data_category: "ConsumerPersonal" }, "x-review-note": "check" })),
      field("tags", ext({ "x-tags": ["a", "b\"c"] })),
      field("note", ext({ "x-securityClassification": { data_class: "classX", data_category: "ConsumerPersonal" } })),
      field("first-name", ext({ "x-lineage": { source: { system: "crm", ratio: 0.5, live: true }, hops: [{ name: "a" }, { name: "b" }] } })),
    ],
    { "x-owner": { team: "crm", tier: 2, contacts: ["a@x", "b@x"] } }
  );
  const defs = [PACK_DEF, OWNER, REVIEW, TAGS, NESTED];

  it("appends the field option in text format and imports the options file", () => {
    const out = annotateProto({ path: "main.proto", content: PROTO }, customer, defs);
    expect(out.content).toContain(
      'string email = 1 [(superschema.metadata.x_security_classification) = { data_class: "class2" data_category: "ConsumerPersonal" }];'
    );
    expect(out.content).toContain('syntax = "proto3";\n\nimport "superschema/metadata_options.proto";\n\n// A customer');
    expect(out.content).not.toContain("x_review_note");
  });

  it("repeated top-level options, nested values, the entity option inside the message", () => {
    const out = annotateProto({ path: "main.proto", content: PROTO }, customer, defs);
    expect(out.content).toContain('repeated string tags = 2 [(superschema.metadata.x_tags) = "a", (superschema.metadata.x_tags) = "b\\"c"];');
    expect(out.content).toContain(
      'string first_name = 4 [(superschema.metadata.x_lineage) = { source: { system: "crm" ratio: 0.5 live: true } hops: [{ name: "a" }, { name: "b" }] }];'
    );
    expect(out.content).toContain('message Customer {\n  option (superschema.metadata.x_owner) = { team: "crm" tier: 2 contacts: ["a@x", "b@x"] };\n  string email = 1');
  });

  it("a value that fails its value schema is skipped with a warning naming the field and the key", () => {
    const warnings: string[] = [];
    const out = annotateProto({ path: "main.proto", content: PROTO }, customer, defs, { warnings });
    expect(out.content).toContain("  string note = 3;\n");
    expect(warnings).toHaveLength(1);
    expect(warnings[0]).toContain('"note"');
    expect(warnings[0]).toContain("x-securityClassification");
  });

  it("reports the used keys, and the annotated proto parses with the options proto", () => {
    const used = new Set<string>();
    const out = annotateProto({ path: "main.proto", content: PROTO }, customer, defs, { used });
    expect([...used].sort()).toEqual(["x-lineage", "x-owner", "x-securityClassification", "x-tags"]);
    const options = buildOptionsProto(defs, used);
    const root = parseTogether(options.content, out.content);
    const email = root.lookupType("Customer").fields.email;
    expect(email.options?.["(superschema.metadata.x_security_classification).data_class"]).toBe("class2");
  });

  it("nothing to annotate: the same file object", () => {
    const file = { path: "main.proto", content: PROTO };
    expect(annotateProto(file, model([field("email")]), defs)).toBe(file);
    expect(annotateProto(file, customer, [REVIEW])).toBe(file);
  });
});
