import { describe, expect, it } from "vitest";
import { TEMPLATES } from "@/lib/events/templates";
import type { FieldTemplate, ObjectTemplateId } from "@/lib/events/templates";
import { collectSpecProperties, specDefinition } from "./spec-helpers";

/** Template id -> AsyncAPI 3.0.0 definition name(s) it must cover. `Record<ObjectTemplateId, …>` forces all 18. */
const SPEC_DEFINITIONS: Record<ObjectTemplateId, string[]> = {
  info: ["info"],
  contact: ["contact"],
  license: ["license"],
  externalDocs: ["externalDocs"],
  tag: ["tag"],
  server: ["server"],
  serverVariable: ["serverVariable"],
  channel: ["channel"],
  channelParameter: ["parameter"],
  operation: ["operation"],
  operationReply: ["operationReply"],
  operationReplyAddress: ["operationReplyAddress"],
  operationTrait: ["operationTrait"],
  message: ["messageObject"],
  messageTrait: ["messageTrait"],
  messageExample: ["messageExampleObject"],
  correlationId: ["correlationId"],
  // The security scheme is a union of per-type definitions; its template is the union of their properties.
  securityScheme: [
    "userPassword", "apiKey", "X509", "symmetricEncryption", "asymmetricEncryption", "NonBearerHTTPSecurityScheme",
    "BearerHTTPSecurityScheme", "APIKeyHTTPSecurityScheme", "oauth2Flows", "openIdConnect", "SaslPlainSecurityScheme",
    "SaslScramSecurityScheme", "SaslGssapiSecurityScheme",
  ],
};
const TEMPLATE_IDS = Object.keys(SPEC_DEFINITIONS) as ObjectTemplateId[];

/** Spec properties a template deliberately does not list ("<templateId>.<property>" -> reason). */
const IGNORED: Record<string, string> = {
  "info.version": "generated by the system (the event version), never typed by the user",
};

/** Template fields that are not AsyncAPI properties ("<templateId>.<key>" -> reason). */
const EXTRA_FIELDS: Record<string, string> = {
  "message.keyPin": "Super Schema pins an entity as the message key (emitted into the Kafka message binding)",
};

/** Properties the spec does not require but Super Schema does ("<templateId>.<key>" -> reason). */
const EXTRA_REQUIRED: Record<string, string> = {
  "message.payload": "every Super Schema message points at an entity for its payload",
};

const spec = (id: ObjectTemplateId) => {
  const properties: Record<string, ReturnType<typeof collectSpecProperties>["properties"][string]> = {};
  const required = new Set<string>();
  for (const name of SPEC_DEFINITIONS[id]) {
    const one = collectSpecProperties(name);
    Object.assign(properties, one.properties);
    one.required.forEach((k) => required.add(k));
  }
  return { properties, required };
};

const walk = (fields: FieldTemplate[], visit: (field: FieldTemplate, trail: string) => void, trail = "") => {
  for (const field of fields) {
    visit(field, `${trail}${field.key}`);
    if (field.fields) walk(field.fields, visit, `${trail}${field.key}.`);
  }
};

describe("TEMPLATES catalog", () => {
  it("has a template for every ObjectTemplateId, keyed by its own id", () => {
    expect(Object.keys(TEMPLATES).sort()).toEqual([...TEMPLATE_IDS].sort());
    for (const id of TEMPLATE_IDS) {
      expect(TEMPLATES[id].id).toBe(id);
      expect(TEMPLATES[id].label.length).toBeGreaterThan(0);
    }
  });

  describe.each(TEMPLATE_IDS)("%s", (id) => {
    const template = TEMPLATES[id];
    const { properties, required } = spec(id);
    const keys = template.fields.map((f) => f.key);

    it("lists every non-x- property of the spec object (minus the IGNORED map)", () => {
      const missing = Object.keys(properties).filter((p) => !keys.includes(p) && !(`${id}.${p}` in IGNORED));
      expect(missing).toEqual([]);
    });

    it("lists nothing the spec does not define, unless it is in EXTRA_FIELDS", () => {
      const unknown = keys.filter((k) => !(k in properties) && !(`${id}.${k}` in EXTRA_FIELDS));
      expect(unknown).toEqual([]);
    });

    it("never lists an IGNORED property", () => {
      const ignored = Object.keys(IGNORED).filter((entry) => entry.startsWith(`${id}.`)).map((entry) => entry.slice(id.length + 1));
      for (const key of ignored) expect(keys).not.toContain(key);
    });

    it("marks exactly the spec-required properties as required (plus EXTRA_REQUIRED)", () => {
      const specRequired = [...required].filter((key) => !(`${id}.${key}` in IGNORED));
      const expected = new Set([...specRequired, ...Object.keys(EXTRA_REQUIRED).filter((e) => e.startsWith(`${id}.`)).map((e) => e.slice(id.length + 1))]);
      const actual = new Set(template.fields.filter((f) => f.required).map((f) => f.key));
      expect([...actual].sort()).toEqual([...expected].sort());
    });

    it("has unique keys, a label and a plain-language help on every field at every depth", () => {
      expect(new Set(keys).size).toBe(keys.length);
      walk(template.fields, (field, trail) => {
        expect(field.label.trim(), `${id}.${trail} label`).not.toBe("");
        expect(field.help?.trim().length ?? 0, `${id}.${trail} help`).toBeGreaterThan(0);
        expect(field.help!.length, `${id}.${trail} help length`).toBeLessThanOrEqual(320);
        expect(["basics", "more"], `${id}.${trail} group`).toContain(field.group);
      });
    });

    it("keeps every basics field in the spec (or EXTRA_FIELDS) and every required field in basics", () => {
      for (const field of template.fields) {
        if (field.group === "basics") expect(field.key in properties || `${id}.${field.key}` in EXTRA_FIELDS, field.key).toBe(true);
        if (field.required) expect(field.group, `${field.key} is required so it belongs in basics`).toBe("basics");
      }
      expect(template.fields.some((f) => f.group === "basics")).toBe(true);
    });

    it("gives enum fields options, container fields their item shape, and reference fields a target", () => {
      walk(template.fields, (field, trail) => {
        if (field.kind === "enum") expect(field.options?.length, `${id}.${trail} options`).toBeGreaterThan(0);
        if (field.kind === "object" || field.kind === "list") expect(field.fields?.length, `${id}.${trail} fields`).toBeGreaterThan(0);
        if (field.kind === "reference") expect(field.refersTo, `${id}.${trail} refersTo`).toBeDefined();
      });
    });
  });

  describe("the basics group (what people fill daily)", () => {
    const basics = (id: ObjectTemplateId) => TEMPLATES[id].fields.filter((f) => f.group === "basics").map((f) => f.key);
    it("server", () => expect(basics("server")).toEqual(expect.arrayContaining(["host", "protocol", "protocolVersion", "pathname", "description", "title"])));
    it("channel", () => expect(basics("channel")).toEqual(expect.arrayContaining(["address", "title", "summary", "description", "servers", "parameters"])));
    it("message", () => expect(basics("message")).toEqual(expect.arrayContaining(["name", "title", "summary", "description", "contentType", "correlationId", "examples"])));
    it("keeps the rarely used server properties under more", () => {
      const more = TEMPLATES.server.fields.filter((f) => f.group === "more").map((f) => f.key);
      expect(more).toEqual(expect.arrayContaining(["summary", "variables", "security", "tags", "externalDocs", "bindings"]));
    });
  });

  describe("info", () => {
    it("covers title, description, termsOfService, contact, license, tags, externalDocs and omits the generated version", () => {
      expect(TEMPLATES.info.fields.map((f) => f.key)).toEqual(["title", "description", "termsOfService", "contact", "license", "tags", "externalDocs"]);
    });
  });

  describe("nested shapes reuse the object templates", () => {
    const field = (id: ObjectTemplateId, key: string) => TEMPLATES[id].fields.find((f) => f.key === key)!;
    it.each([
      ["info", "contact", "object", "contact"],
      ["info", "license", "object", "license"],
      ["info", "externalDocs", "object", "externalDocs"],
      ["info", "tags", "tags", "tag"],
      ["server", "variables", "list", "serverVariable"],
      ["server", "tags", "tags", "tag"],
      ["server", "externalDocs", "object", "externalDocs"],
      ["channel", "parameters", "list", "channelParameter"],
      ["channel", "tags", "tags", "tag"],
      ["operation", "reply", "object", "operationReply"],
      ["operation", "tags", "tags", "tag"],
      ["operationReply", "address", "object", "operationReplyAddress"],
      ["message", "correlationId", "object", "correlationId"],
      ["message", "examples", "list", "messageExample"],
      ["messageTrait", "correlationId", "object", "correlationId"],
      ["messageTrait", "examples", "list", "messageExample"],
      ["tag", "externalDocs", "object", "externalDocs"],
    ] as const)("%s.%s is a %s shaped like the %s template", (host, key, kind, target) => {
      const f = field(host, key);
      expect(f.kind).toBe(kind);
      expect(f.fields).toEqual(TEMPLATES[target].fields);
    });
  });

  describe("maps keyed by a user-chosen name", () => {
    it("server variables and channel parameters say what the key is", () => {
      expect(TEMPLATES.server.fields.find((f) => f.key === "variables")?.mapKeyLabel).toBeTruthy();
      expect(TEMPLATES.channel.fields.find((f) => f.key === "parameters")?.mapKeyLabel).toBeTruthy();
    });
  });

  describe("references", () => {
    const refs = (id: ObjectTemplateId) => Object.fromEntries(TEMPLATES[id].fields.filter((f) => f.kind === "reference").map((f) => [f.key, `${f.refersTo}${f.multiple ? "[]" : ""}`]));
    it("server.security points at security schemes", () => expect(refs("server")).toEqual({ security: "securityScheme[]" }));
    it("channel points at servers and messages", () => expect(refs("channel")).toEqual({ servers: "server[]", messages: "message[]" }));
    it("operation points at one channel, messages and traits", () =>
      expect(refs("operation")).toEqual({ channel: "channel", messages: "message[]", traits: "operationTrait[]", security: "securityScheme[]" }));
    it("operation reply points at one channel and messages", () => expect(refs("operationReply")).toEqual({ channel: "channel", messages: "message[]" }));
    it("message points at message traits", () => expect(refs("message")).toEqual({ traits: "messageTrait[]" }));
    it("operation traits point at security schemes", () => expect(refs("operationTrait")).toEqual({ security: "securityScheme[]" }));
    it("the operation channel is required", () => expect(TEMPLATES.operation.fields.find((f) => f.key === "channel")?.required).toBe(true));
  });

  describe("entity pins", () => {
    it.each(["message", "messageTrait"] as const)("%s headers is an entity pin", (id) => {
      expect(TEMPLATES[id].fields.find((f) => f.key === "headers")?.kind).toBe("entityPin");
    });
    it("message payload and key are entity pins and the payload is required", () => {
      const payload = TEMPLATES.message.fields.find((f) => f.key === "payload");
      expect(payload?.kind).toBe("entityPin");
      expect(payload?.required).toBe(true);
      expect(TEMPLATES.message.fields.find((f) => f.key === "keyPin")?.kind).toBe("entityPin");
    });
  });

  describe("enum options come from the spec", () => {
    it("operation.action is send | receive", () => {
      const options = TEMPLATES.operation.fields.find((f) => f.key === "action")!.options!.map((o) => o.value);
      expect(options).toEqual(specDefinition("operation").properties!.action.enum);
    });

    it("securityScheme.type lists every scheme type of the spec, with help for each", () => {
      const fromSpec = new Set<string>();
      for (const name of SPEC_DEFINITIONS.securityScheme) for (const v of collectSpecProperties(name).properties.type.enum ?? []) fromSpec.add(v);
      const type = TEMPLATES.securityScheme.fields.find((f) => f.key === "type")!;
      expect(type.kind).toBe("enum");
      expect(type.options!.map((o) => o.value).sort()).toEqual([...fromSpec].sort());
      expect(fromSpec.size).toBe(13);
      for (const option of type.options!) expect(option.help?.length ?? 0, option.value).toBeGreaterThan(0);
    });

    it("securityScheme.in lists the apiKey and httpApiKey locations", () => {
      const inField = TEMPLATES.securityScheme.fields.find((f) => f.key === "in")!;
      expect(inField.options!.map((o) => o.value).sort()).toEqual(["cookie", "header", "password", "query", "user"]);
    });
  });

  describe("securityScheme is a union of per-type definitions", () => {
    const typeValues = (definition: string) => collectSpecProperties(definition).properties.type.enum ?? [];
    const template = TEMPLATES.securityScheme;

    it("shows each type-specific property only for the types that define it", () => {
      for (const field of template.fields) {
        const types = new Set<string>();
        for (const definition of SPEC_DEFINITIONS.securityScheme) {
          if (field.key in collectSpecProperties(definition).properties) typeValues(definition).forEach((t) => types.add(t));
        }
        const universal = types.size === 13;
        if (universal) expect(field.when, `${field.key} applies to every type`).toBeUndefined();
        else {
          expect(field.when?.field, field.key).toBe("type");
          expect([...field.when!.oneOf].sort(), field.key).toEqual([...types].sort());
        }
      }
    });

    it("marks a property required when any type requires it (it is then required for the types it is shown for)", () => {
      const requiredAnywhere = new Set(SPEC_DEFINITIONS.securityScheme.flatMap((d) => collectSpecProperties(d).required));
      expect(new Set(template.fields.filter((f) => f.required).map((f) => f.key))).toEqual(requiredAnywhere);
    });

    it("describes each oauth2 flow with exactly the urls and scopes the spec allows, and requires what the spec requires", () => {
      const flows = template.fields.find((f) => f.key === "flows")!;
      expect(flows.kind).toBe("object");
      expect(flows.fields!.map((f) => f.key)).toEqual(["implicit", "password", "clientCredentials", "authorizationCode"]);
      const flowProperties = collectSpecProperties("oauth2Flow").properties;
      const specFlows = collectSpecProperties("oauth2Flows").properties.flows.properties!;
      for (const flow of flows.fields!) {
        expect(flow.kind, flow.key).toBe("object");
        const branches = specFlows[flow.key].allOf!;
        const required = branches.flatMap((b) => b.required ?? []);
        const forbidden = branches.flatMap((b) => b.not?.required ?? []);
        const allowed = Object.keys(flowProperties).filter((p) => !forbidden.includes(p));
        expect(flow.fields!.map((f) => f.key), `${flow.key} allowed`).toEqual(allowed);
        expect(flow.fields!.filter((f) => f.required).map((f) => f.key), `${flow.key} required`).toEqual(allowed.filter((p) => required.includes(p)));
        expect(flow.fields!.find((f) => f.key === "availableScopes")!.kind).toBe("keyValue");
      }
      // Spot-check the spec reading: an implicit flow has no token URL, a client-credentials flow no authorization URL.
      expect(flows.fields!.find((f) => f.key === "implicit")!.fields!.map((f) => f.key)).not.toContain("tokenUrl");
      expect(flows.fields!.find((f) => f.key === "clientCredentials")!.fields!.map((f) => f.key)).not.toContain("authorizationUrl");
    });
  });

  describe("suggestions", () => {
    it("server.protocol suggests the common protocols", () => {
      const suggestions = TEMPLATES.server.fields.find((f) => f.key === "protocol")!.suggestions!;
      expect(suggestions).toEqual(expect.arrayContaining([
        "kafka", "googlepubsub", "pulsar", "amqp", "amqps", "mqtt", "mqtts", "nats", "redis", "sns", "sqs", "ws", "wss", "http", "https",
        "jms", "stomp", "solace", "ibmmq", "anypointmq", "mercure", "ros2",
      ]));
    });

    it.each(["message", "messageTrait"] as const)("%s.contentType suggests common media types", (id) => {
      const suggestions = TEMPLATES[id].fields.find((f) => f.key === "contentType")!.suggestions!;
      expect(suggestions).toEqual(expect.arrayContaining([
        "application/json", "application/avro", "avro/binary", "application/x-protobuf", "application/cloudevents+json", "text/plain",
      ]));
    });

    it("correlation id and reply address locations suggest runtime expressions", () => {
      expect(TEMPLATES.correlationId.fields.find((f) => f.key === "location")!.suggestions!.every((s) => s.startsWith("$message."))).toBe(true);
      expect(TEMPLATES.operationReplyAddress.fields.find((f) => f.key === "location")!.suggestions!.every((s) => s.startsWith("$message."))).toBe(true);
    });
  });

  describe("field kinds follow the spec formats", () => {
    const kind = (id: ObjectTemplateId, key: string) => TEMPLATES[id].fields.find((f) => f.key === key)!.kind;
    it("uses url for uri properties and email for emails", () => {
      expect(kind("info", "termsOfService")).toBe("url");
      expect(kind("contact", "url")).toBe("url");
      expect(kind("contact", "email")).toBe("email");
      expect(kind("license", "url")).toBe("url");
      expect(kind("externalDocs", "url")).toBe("url");
      expect(kind("securityScheme", "openIdConnectUrl")).toBe("url");
    });
    it("uses markdown for CommonMark descriptions, boolean for deprecated, stringList for enums/examples", () => {
      expect(kind("server", "description")).toBe("markdown");
      expect(kind("message", "deprecated")).toBe("boolean");
      expect(kind("serverVariable", "enum")).toBe("stringList");
      expect(kind("serverVariable", "examples")).toBe("stringList");
      expect(kind("channelParameter", "enum")).toBe("stringList");
    });
    it("keeps bindings as json (protocol forms come from bindingTemplate)", () => {
      for (const id of ["server", "channel", "operation", "operationTrait", "message", "messageTrait"] as const) expect(kind(id, "bindings")).toBe("json");
    });
  });
});
