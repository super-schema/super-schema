/** Renders the corpus results as the markdown matrix report. */
import { KNOWN_ISSUES } from "../../fixtures/corpus/known-issues";
import type { TargetKey } from "../../fixtures/corpus/types";
import type { CaseResult } from "./orchestrate";

const SYMBOL: Record<string, string> = { PASS: "P", DEGRADED: "D", NEEDS_INPUT: "N", FAIL: "F", SKIPPED: "S" };
const RT: Record<string, string> = { SAME: "same", EXPECTED_DIFF: "expected", OPEN_DIFF: "OPEN", DEFECT: "DEFECT", SKIPPED: "-", REIMPORT_FAILED: "REIMPORT" };

export interface MatrixMeta { runId: string; targets: TargetKey[]; emulators: { spanner: boolean; bigquery: boolean; reasons: string[] }; ms: number; cleanup: { spanner: string[]; bigquery: string[]; created: { spanner: number; bigquery: number } } }

const signature = (reason: string): string => reason.replace(/\d+/g, "N").replace(/"[^"]*"/g, '"…"').replace(/`[^`]*`/g, "`…`").slice(0, 120);

export function renderMatrix(results: CaseResult[], meta: MatrixMeta): string {
  const lines: string[] = [];
  lines.push("# Corpus matrix", "");
  lines.push(`Generated by \`npm run test:corpus\` (run id \`${meta.runId}\`, ${Math.round(meta.ms / 1000)} s, ${results.length} cases x ${meta.targets.length} targets).`, "");
  lines.push("Legend: P = PASS, D = DEGRADED (generated with the app's warning), N = NEEDS_INPUT (a primary key must be chosen and no field is eligible), F = FAIL, S = SKIPPED; `F*` = FAIL that is a known issue (see below). Round trip: same / expected (documented lossy mapping) / DEFECT.", "");
  lines.push(`Emulators: spanner ${meta.emulators.spanner ? "used" : "NOT used"}, bigquery ${meta.emulators.bigquery ? "used" : "NOT used"}${meta.emulators.reasons.length ? ` (${meta.emulators.reasons.join("; ")})` : ""}.`, "");

  lines.push("## Totals per target", "", `| target | PASS | DEGRADED | NEEDS_INPUT | FAIL | FAIL (known) | SKIPPED | validator tier |`, "|---|---|---|---|---|---|---|---|");
  for (const t of meta.targets) {
    const count = (kind: string, known?: boolean): number => results.filter((r) => { const o = r.targets[t]; return o?.kind === kind && (known === undefined || Boolean(o.expected) === known); }).length;
    const tier = results.map((r) => r.targets[t]?.validator).find((v) => v) ?? "-";
    lines.push(`| ${t} | ${count("PASS")} | ${count("DEGRADED")} | ${count("NEEDS_INPUT")} | ${count("FAIL", false)} | ${count("FAIL", true)} | ${count("SKIPPED")} | ${tier} |`);
  }
  const buildFailures = results.filter((r) => !r.build.ok && !r.importRefused);
  lines.push("", `Cases whose import was refused as the case expects: ${results.filter((r) => r.importRefused).length}. Cases whose rows could not be built unexpectedly: ${buildFailures.length}.`);

  const rtCount = (s: string): number => results.filter((r) => r.roundTrip?.status === s).length;
  const comparable = ["SAME", "EXPECTED_DIFF", "OPEN_DIFF", "DEFECT"].reduce((n, st) => n + rtCount(st), 0);
  lines.push("", "## Round trip (JSON Schema cases)", "", `Comparable (re-import produced a schema to compare): ${comparable} = same ${rtCount("SAME")} + expected differences ${rtCount("EXPECTED_DIFF")} + OPEN (design question) ${rtCount("OPEN_DIFF")} + DEFECT ${rtCount("DEFECT")}. Not comparable: re-import failed ${rtCount("REIMPORT_FAILED")}, skipped ${rtCount("SKIPPED")} (the case's json-schema output is a known failure). Skipped cases: ${results.filter((r) => r.roundTrip?.status === "SKIPPED").map((r) => r.id).join(", ") || "none"}.`, "");
  const diffs = results.filter((r) => r.roundTrip && r.roundTrip.differences.length > 0);
  if (diffs.length > 0) {
    lines.push("| case | status | difference |", "|---|---|---|");
    for (const r of diffs) for (const d of r.roundTrip!.differences.slice(0, 4)) lines.push(`| ${r.id} | ${d.classification}${d.why ? ` (${d.why})` : ""} | \`${d.path}\`: ${JSON.stringify(d.before)?.slice(0, 60)} -> ${JSON.stringify(d.after)?.slice(0, 60)} |`);
    lines.push("");
  }

  lines.push("## Failures grouped by root cause", "");
  const groups = new Map<string, { target: string; expected?: string; cases: string[] }>();
  for (const r of results) for (const [t, o] of Object.entries(r.targets)) {
    if (o?.kind !== "FAIL") continue;
    const key = `${t} | ${o.expected ? "KNOWN " : ""}${signature(o.reason ?? "")}`;
    const g = groups.get(key) ?? { target: t, expected: o.expected, cases: [] };
    g.cases.push(r.id); groups.set(key, g);
  }
  if (groups.size === 0) lines.push("None.", "");
  for (const [key, g] of [...groups].sort((a, b) => b[1].cases.length - a[1].cases.length)) {
    lines.push(`- **${key}** (${g.cases.length}): ${g.cases.slice(0, 6).join(", ")}${g.cases.length > 6 ? ", ..." : ""}${g.expected ? `\n  - known: ${g.expected}` : ""}`);
  }
  lines.push("", "## Known issues (not defects of this repo)", "");
  for (const k of KNOWN_ISSUES) {
    const hits = results.filter((r) => Object.values(r.targets).some((o) => o?.expected?.startsWith(`${k.id}:`))).length;
    lines.push(`- \`${k.id}\` [${k.disposition}] (${k.targets.length === 8 ? "all targets" : k.targets.join(", ")}; owner: ${k.owner}; ${hits} cases): ${k.issue}`);
  }
  lines.push("", "## Emulator cleanup", "", `Created and dropped: ${meta.cleanup.created.spanner} Spanner databases (prefix \`sscorp_${meta.runId}_\`), ${meta.cleanup.created.bigquery} BigQuery datasets (prefix \`ss_corpus_${meta.runId}_\`). Left after the final sweep: Spanner [${meta.cleanup.spanner.join(", ")}], BigQuery [${meta.cleanup.bigquery.join(", ")}].`, "");

  lines.push("## Matrix", "", `| case | kind | ${meta.targets.join(" | ")} | round trip |`, `|---|---|${meta.targets.map(() => "---").join("|")}|---|`);
  for (const r of results) {
    const cells = meta.targets.map((t) => { const o = r.targets[t]; return o ? `${SYMBOL[o.kind]}${o.kind === "FAIL" && o.expected ? "*" : ""}` : "?"; });
    lines.push(`| ${r.id} | ${r.kind} | ${cells.join(" | ")} | ${r.roundTrip ? RT[r.roundTrip.status] : r.build.ok ? "-" : r.importRefused ? "import refused (expected)" : "build failed"} |`);
  }
  lines.push("", "## Non-pass details", "", "| case | target | outcome | detail |", "|---|---|---|---|");
  for (const r of results) {
    if (!r.build.ok) lines.push(`| ${r.id} | - | ${r.importRefused ? "IMPORT REFUSED (expected)" : "BUILD FAILED"} | ${r.build.reason.replace(/\|/g, "/").slice(0, 160)} |`);
    for (const [t, o] of Object.entries(r.targets)) {
      if (!o || o.kind === "PASS") continue;
      lines.push(`| ${r.id} | ${t} | ${o.kind}${o.expected ? " (known)" : ""} | ${(o.reason ?? "").replace(/\s+/g, " ").replace(/\|/g, "/").slice(0, 160)} |`);
    }
  }
  lines.push("");
  return lines.join("\n");
}
